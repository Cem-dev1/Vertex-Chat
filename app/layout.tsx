import type { Metadata } from "next";
import { Open_Sans } from "next/font/google";
import "./globals.css";
import { ClerkProvider } from "@clerk/nextjs";
import { ThemeProvider } from "@/components/providers/theme-provider";
import { cn } from "@/lib/utils";
import { ModalProvider } from "@/components/providers/modal-provider";
import { SocketProvider } from "@/components/providers/socket-provider";
import { QueryProvider } from "@/components/providers/query-provider";

const font = Open_Sans({
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Sohbet demo",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <ClerkProvider>
      {/* html ve body etiketlerinde suppressHydrationWarning olması önemli */}
      <html lang="en" suppressHydrationWarning>
        <body className={cn(
          font.className,
          // bg-white ve dark mode rengini buraya net veriyoruz
          "bg-white dark:bg-[#313338]"
        )}>
          <ThemeProvider 
            attribute="class"
            defaultTheme="dark" // Varsayılanı dark yaptığın için modal bazen karanlıkta kalıyor olabilir
            enableSystem={false}
            storageKey="discord-theme" //modalprovider eklencek children ustune 
          >
         <QueryProvider>
            <SocketProvider>
              <ModalProvider />
                {children}
             </SocketProvider>
           </QueryProvider>
          </ThemeProvider>
        </body>
      </html>
    </ClerkProvider>
  );
}
